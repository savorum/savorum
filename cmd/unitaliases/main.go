// Command unitaliases publishes the SREF unit registry's alias vocabulary to
// internal/units, so the parser reads the same forms the registry declares in
// every language rather than a hand-kept copy.
//
// The registry is read from SREF_REGISTRY_PATH, or from the sibling SREF
// checkout. With --check the command fails when the checked-in file differs,
// and skips when no registry is available unless SREF_REQUIRED is set.
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/savorum/savorum/internal/codegen"
	"github.com/savorum/savorum/internal/srefcheckout"
)

const command = "go run ./cmd/unitaliases"

type registry struct {
	Units []struct {
		ID      string `json:"id"`
		Status  string `json:"status"`
		Aliases []struct {
			Language      string   `json:"language"`
			Forms         []string `json:"forms"`
			CaseSensitive bool     `json:"case_sensitive"`
		} `json:"aliases"`
	} `json:"units"`
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(arguments []string) error {
	flags := flag.NewFlagSet("unitaliases", flag.ContinueOnError)
	flags.SetOutput(os.Stderr)
	output := flags.String("output", "internal/units/aliases_generated.go", "alias vocabulary output path")
	check := flags.Bool("check", false, "verify that the output file is current")

	if err := flags.Parse(arguments); err != nil {
		return fmt.Errorf("parse command flags: %w", err)
	}

	if flags.NArg() != 0 {
		return fmt.Errorf("unexpected argument %q", flags.Arg(0))
	}

	data, err := os.ReadFile(registryPath())
	if err != nil {
		if *check && errors.Is(err, fs.ErrNotExist) && os.Getenv("SREF_REQUIRED") == "" {
			fmt.Fprintln(os.Stderr, "unitaliases: no SREF registry beside this repository; skipping the check")

			return nil
		}

		return fmt.Errorf("read the SREF registry: %w", err)
	}

	rendered, err := render(data)
	if err != nil {
		return err
	}

	if *check {
		return codegen.CheckArtifact(*output, rendered, command)
	}

	return codegen.WriteArtifact(*output, rendered)
}

func registryPath() string {
	if path := os.Getenv("SREF_REGISTRY_PATH"); path != "" {
		return path
	}

	root, err := srefcheckout.Locate()
	if err != nil {
		root = filepath.Join("..", "sref")
	}

	return filepath.Join(root, "registry", "units.json")
}

func render(data []byte) ([]byte, error) {
	var parsed registry
	if err := json.Unmarshal(data, &parsed); err != nil {
		return nil, fmt.Errorf("decode the SREF registry: %w", err)
	}

	var out strings.Builder
	out.WriteString("// Code generated by " + command + "; DO NOT EDIT.\n\n")
	out.WriteString("package units\n\n")
	out.WriteString("// defaultAliasSets is the alias vocabulary of the SREF unit registry, in the\n")
	out.WriteString("// order the registry declares it.\n")
	out.WriteString("func defaultAliasSets() []AliasSet {\n\treturn []AliasSet{\n")

	for _, unit := range parsed.Units {
		if unit.Status != "active" {
			continue
		}

		for _, set := range unit.Aliases {
			constructor := "aliases"
			if set.CaseSensitive {
				constructor = "exactAliases"
			}

			out.WriteString("\t\t" + constructor + "(" + strconv.Quote(unit.ID) + ", " + strconv.Quote(set.Language))

			for _, form := range set.Forms {
				out.WriteString(", " + strconv.Quote(form))
			}

			out.WriteString("),\n")
		}
	}

	out.WriteString("\t}\n}\n")

	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("format the generated vocabulary: %w", err)
	}

	return formatted, nil
}

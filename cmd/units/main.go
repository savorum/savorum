// Command units publishes the canonical unit registry and its display policy
// to the frontend, so the browser, the server, and the document renderer share
// one source of identities, conversion factors, labels, and rounding ladders.
// Which measures an editor offers first remains frontend policy.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/savorum/savorum/internal/codegen"
	"github.com/savorum/savorum/internal/recipe"
	"github.com/savorum/savorum/internal/units"
)

const command = "go run ./cmd/units"

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(arguments []string) error {
	flags := flag.NewFlagSet("units", flag.ContinueOnError)
	flags.SetOutput(os.Stderr)
	output := flags.String("output", "web/src/lib/unit-registry.generated.ts", "unit registry output path")

	check := flags.Bool("check", false, "verify that the output file is current")
	if err := flags.Parse(arguments); err != nil {
		return fmt.Errorf("parse command flags: %w", err)
	}

	if flags.NArg() != 0 {
		return fmt.Errorf("unexpected argument %q", flags.Arg(0))
	}

	rendered := render(units.DefaultCatalog().Entries())
	if *check {
		if err := codegen.CheckArtifact(*output, rendered, command); err != nil {
			return err
		}
	} else if err := codegen.WriteArtifact(*output, rendered); err != nil {
		return err
	}

	return writeLocalizedLabels(filepath.Dir(*output), *check)
}

func writeLocalizedLabels(directory string, check bool) error {
	if !check {
		if err := os.MkdirAll(filepath.Join(directory, "unit-locales"), 0o750); err != nil {
			return fmt.Errorf("create unit locale directory: %w", err)
		}
	}

	catalogs := units.LocalizedLabelCatalogs()

	locales := make([]string, 0, len(catalogs))
	for locale := range catalogs {
		locales = append(locales, locale)
	}

	slices.Sort(locales)

	var index strings.Builder
	index.WriteString("// Code generated by " + command + "; DO NOT EDIT.\nexport const unitLabelLoaders = {\n")

	write := func(path string, data []byte) error {
		if check {
			return codegen.CheckArtifact(path, data, command)
		}

		return codegen.WriteArtifact(path, data)
	}
	for _, locale := range locales {
		data, err := json.Marshal(catalogs[locale])
		if err != nil {
			return fmt.Errorf("encode unit locale %s: %w", locale, err)
		}

		data = append([]byte("// Code generated by "+command+"; DO NOT EDIT.\nexport default "), data...)

		data = append(data, '\n')
		if err := write(filepath.Join(directory, "unit-locales", locale+".generated.ts"), data); err != nil {
			return err
		}

		fmt.Fprintf(&index, "  %q: () => import(%q),\n", locale, "./unit-locales/"+locale+".generated.ts")
	}

	index.WriteString("}\n")

	return write(filepath.Join(directory, "unit-locales.generated.ts"), []byte(index.String()))
}

func render(entries []units.Entry) []byte {
	var out strings.Builder
	out.WriteString("// Code generated by " + command + "; DO NOT EDIT.\n")
	out.WriteString("//\n")
	out.WriteString("// The canonical unit registry, published from internal/units so the browser\n")
	out.WriteString("// converts through the same definitions the server validates against. Amounts\n")
	out.WriteString("// are canonical rationals rather than decimals, because a culinary measure\n")
	out.WriteString("// must never pass through a float. How a unit is written for a cook is\n")
	out.WriteString("// presentation policy, and it is published from internal/units too, so the\n")
	out.WriteString("// recipe on screen and the printed document round an amount the same way.\n\n")
	out.WriteString("export type UnitKind = 'physical' | 'count' | 'container'\n\n")
	out.WriteString("export type UnitDimension = 'mass' | 'volume' | 'length' | 'temperature'\n\n")
	out.WriteString("/**\n")
	out.WriteString(" * The culinary measuring convention a unit belongs to. Not a geography:\n")
	out.WriteString(" * Australia measures metrically and still keeps a 250 mL cup.\n")
	out.WriteString(" */\n")
	// Imperial is a convention but not a MeasurementSystem a reader can choose.
	out.WriteString("export type UnitConvention = 'metric' | 'us' | 'au' | 'imperial'\n\n")
	out.WriteString("/**\n")
	out.WriteString(" * Every identity the server accepts. Typing presentation tables against this\n")
	out.WriteString(" * union is what makes a unit added to the catalog a compile error here until\n")
	out.WriteString(" * the frontend can say it out loud.\n")
	out.WriteString(" */\n")
	out.WriteString("export type UnitId =\n")

	for _, entry := range entries {
		out.WriteString("  | " + quote(entry.Unit.ID) + "\n")
	}

	out.WriteString("\n")
	out.WriteString("export interface RegistryUnit {\n")
	out.WriteString("  id: UnitId\n")
	out.WriteString("  kind: UnitKind\n")
	out.WriteString("  /** Present only for a unit with a physical definition. */\n")
	out.WriteString("  dimension?: UnitDimension\n")
	out.WriteString("  /** The measuring convention the unit belongs to, when it has one. */\n")
	out.WriteString("  convention?: UnitConvention\n")
	out.WriteString("  /** The unit this dimension is measured in. */\n")
	out.WriteString("  base?: string\n")
	out.WriteString("  /** Base units in one of this unit, as `n` or `n/d`. */\n")
	out.WriteString("  factor?: string\n")
	out.WriteString("  /** Added after scaling, for scales that do not share an origin. */\n")
	out.WriteString("  offset?: string\n")
	out.WriteString("  /** False when the definition is itself a culinary approximation. */\n")
	out.WriteString("  exact?: boolean\n")
	out.WriteString("}\n\n")
	out.WriteString("export const unitRegistry: readonly RegistryUnit[] = [\n")

	for _, entry := range entries {
		out.WriteString("  { ")
		fmt.Fprintf(&out, "id: %s, kind: %s", quote(entry.Unit.ID), quote(string(entry.Unit.Kind)))

		if entry.Unit.Dimension != "" {
			fmt.Fprintf(&out, ", dimension: %s", quote(string(entry.Unit.Dimension)))
		}

		if entry.Convention != units.ConventionNone {
			fmt.Fprintf(&out, ", convention: %s", quote(string(entry.Convention)))
		}

		if entry.Unit.Kind == recipe.UnitPhysical {
			fmt.Fprintf(&out, ", base: %s, factor: %s", quote(entry.BaseUnit), quote(entry.Multiplier))

			if entry.Offset != "0" {
				fmt.Fprintf(&out, ", offset: %s", quote(entry.Offset))
			}

			fmt.Fprintf(&out, ", exact: %t", entry.Exact)
		}

		out.WriteString(" },\n")
	}

	out.WriteString("]\n\n")
	renderLabels(&out, entries)
	renderLadders(&out)
	renderVolumePresentation(&out)

	return []byte(out.String())
}

// renderLabels publishes how each identity is written for a cook, typed
// against the identity union so a missing label fails to compile.
func renderLabels(out *strings.Builder, entries []units.Entry) {
	out.WriteString("/** How a unit is written beside an amount. */\n")
	out.WriteString("export interface UnitLabel {\n")
	out.WriteString("  /** Wording for an amount of one or less. */\n")
	out.WriteString("  one: string\n")
	out.WriteString("  many: string\n")
	out.WriteString("  /** Written without a space between the amount and the label. */\n")
	out.WriteString("  tight?: boolean\n")
	out.WriteString("}\n\n")
	out.WriteString("export const unitLabels: Readonly<Record<UnitId, UnitLabel>> = {\n")

	for _, entry := range entries {
		label, found := units.LookupLabel(entry.Unit.ID)
		if !found {
			panic("unit has no label: " + entry.Unit.ID)
		}

		out.WriteString("  " + quote(entry.Unit.ID) + ": { one: " + text(label.One) + ", many: " + text(label.Many))

		if label.Tight {
			out.WriteString(", tight: true")
		}

		out.WriteString(" },\n")
	}

	out.WriteString("}\n\n")
}

// renderLadders publishes the rounding policy.
func renderLadders(out *strings.Builder) {
	systems := []units.MeasurementSystem{units.MeasureMetric, units.MeasureUS, units.MeasureAU}
	dimensions := []recipe.Dimension{
		recipe.DimensionMass, recipe.DimensionVolume,
		recipe.DimensionLength, recipe.DimensionTemperature,
	}

	out.WriteString("export type MeasurementSystem = 'original' | 'metric' | 'us' | 'au'\n\n")
	out.WriteString("/**\n")
	out.WriteString(" * One step of a rounding ladder: the unit a converted amount is written in\n")
	out.WriteString(" * while it stays below the ceiling, and the practical measure it is rounded\n")
	out.WriteString(" * to. The ceiling is stated in the rung's own unit, so this policy never\n")
	out.WriteString(" * restates a conversion factor the registry already holds.\n")
	out.WriteString(" */\n")
	out.WriteString("export interface LadderRung {\n")
	out.WriteString("  unit: UnitId\n")
	out.WriteString("  ceiling?: string\n")
	out.WriteString("  step: string\n")
	out.WriteString("}\n\n")
	out.WriteString("export const measurementLadders: Readonly<\n")
	out.WriteString("  Record<MeasurementSystem, Partial<Record<UnitDimension | 'count', readonly LadderRung[]>>>\n")
	out.WriteString("> = {\n")
	out.WriteString("  original: {},\n")

	ladders := units.Ladders()

	for _, system := range systems {
		out.WriteString("  " + string(system) + ": {\n")

		for _, dimension := range dimensions {
			rungs := ladders[system][dimension]
			if len(rungs) == 0 {
				continue
			}

			out.WriteString("    " + string(dimension) + ": [\n")

			for _, rung := range rungs {
				out.WriteString("      { unit: " + quote(rung.Unit))

				if rung.Ceiling != "" {
					out.WriteString(", ceiling: " + quote(rung.Ceiling))
				}

				out.WriteString(", step: " + quote(rung.Step) + " },\n")
			}

			out.WriteString("    ],\n")
		}

		out.WriteString("  },\n")
	}

	out.WriteString("}\n")
}

// renderVolumePresentation publishes the friendly US/Australian volume policy.
func renderVolumePresentation(out *strings.Builder) {
	policy := units.VolumePresentation()

	out.WriteString("\nexport interface VolumePresentationPolicy {\n")
	out.WriteString("  fractions: readonly (readonly string[])[]\n")
	out.WriteString("  compoundFractions: readonly (readonly string[])[]\n")
	out.WriteString("  remainderSteps: readonly string[]\n")
	out.WriteString("  maxRelativeError: string\n")
	out.WriteString("  maxTeaspoonError: string\n")
	out.WriteString("  relativeErrorWeight: string\n")
	out.WriteString("  minimumSimplicityGain: string\n")
	out.WriteString("}\n\n")
	out.WriteString("export const volumePresentation: VolumePresentationPolicy = {\n")
	renderFractionRungs(out, "fractions", policy.Fractions)
	renderFractionRungs(out, "compoundFractions", policy.CompoundFractions)
	out.WriteString("  remainderSteps: [")

	for index, value := range policy.RemainderSteps {
		if index > 0 {
			out.WriteString(", ")
		}

		out.WriteString(quote(value))
	}

	out.WriteString("],\n")
	out.WriteString("  maxRelativeError: " + quote(policy.MaxRelativeError) + ",\n")
	out.WriteString("  maxTeaspoonError: " + quote(policy.MaxTeaspoonError) + ",\n")
	out.WriteString("  relativeErrorWeight: " + quote(policy.RelativeErrorWeight) + ",\n")
	out.WriteString("  minimumSimplicityGain: " + quote(policy.MinimumSimplicityGain) + ",\n")
	out.WriteString("}\n")
}

// renderFractionRungs writes one per-rung fraction table.
func renderFractionRungs(out *strings.Builder, name string, rungs [][]string) {
	out.WriteString("  " + name + ": [\n")

	for _, rung := range rungs {
		out.WriteString("    [")

		for index, fraction := range rung {
			if index > 0 {
				out.WriteString(", ")
			}

			out.WriteString(quote(fraction))
		}

		out.WriteString("],\n")
	}

	out.WriteString("  ],\n")
}

// text writes a TypeScript string literal for wording that may contain any
// printable character, unlike a registry identity.
func text(value string) string {
	encoded, err := json.Marshal(value)
	if err != nil {
		panic("unit label is not encodable: " + value)
	}

	return string(encoded)
}

// quote writes a TypeScript string literal. Registry identities are constrained
// to lower-case dotted words, so anything needing an escape is a defect in the
// catalog rather than something to encode quietly.
func quote(value string) string {
	if strings.ContainsAny(value, "'\\\n") {
		panic("registry value is not a plain literal: " + value)
	}

	return "'" + value + "'"
}

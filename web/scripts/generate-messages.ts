import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import ts from "typescript"
import type { Plugin } from "vite"

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")
export const compiledMessagesPath = resolve(webRoot, "src/paraglide/messages/_index.js")
const generatedPath = resolve(webRoot, "src/lib/messages.generated.ts")

/** Preserve compiler aliases while exposing statically analyzable message exports. */
export function generateMessages(): void {
  const source = ts.createSourceFile(
    compiledMessagesPath,
    readFileSync(compiledMessagesPath, "utf8"),
    ts.ScriptTarget.Latest,
    false,
    ts.ScriptKind.JS,
  )
  const names = new Map<string, string>()
  for (const statement of source.statements) {
    if (
      ts.isVariableStatement(statement) &&
      statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)
    ) {
      for (const declaration of statement.declarationList.declarations) {
        if (ts.isIdentifier(declaration.name))
          names.set(declaration.name.text, declaration.name.text)
      }
    }
    if (
      ts.isExportDeclaration(statement) &&
      statement.exportClause &&
      ts.isNamedExports(statement.exportClause)
    ) {
      for (const entry of statement.exportClause.elements)
        names.set(entry.name.text, (entry.propertyName ?? entry.name).text)
    }
  }
  if (names.size === 0) throw new Error("Paraglide did not export any messages")
  const english = ts.createSourceFile(
    "en.js",
    readFileSync(resolve(webRoot, "src/paraglide/messages/en.js"), "utf8"),
    ts.ScriptTarget.Latest,
    false,
    ts.ScriptKind.JS,
  )
  const fallbacks = new Map<string, string>()
  for (const statement of english.statements) {
    if (!ts.isVariableStatement(statement)) continue
    for (const declaration of statement.declarationList.declarations) {
      if (ts.isIdentifier(declaration.name) && declaration.initializer)
        fallbacks.set(declaration.name.text, declaration.initializer.getText(english))
    }
  }
  const output = [
    "// Generated by scripts/generate-messages.ts. Do not edit.",
    'import * as registry from "../paraglide/registry.js"',
    'import { localized } from "./message-runtime.ts"',
    'type Messages = typeof import("../paraglide/messages.js").m',
    "",
    ...[...names]
      .sort(([left], [right]) => left.localeCompare(right, "en"))
      .map(([name, key]) => {
        const fallback = fallbacks.get(key)
        if (!fallback) throw new Error(`Missing English compiler output: ${key}`)
        return `export const ${name}: Messages[${JSON.stringify(name)}] = /* @__PURE__ */ localized(${JSON.stringify(key)}, ${fallback})`
      }),
    "",
  ].join("\n")
  let existing = ""
  try {
    existing = readFileSync(generatedPath, "utf8")
  } catch {
    // The first generation has no destination.
  }
  if (existing !== output) writeFileSync(generatedPath, output)
}

/** Bundlers place each message with its consumers instead of one shared catalog. */
export function messageExportsPlugin(): Plugin {
  const prefix = "\0savorum-message/"
  const modules = new Map<string, string>()
  let building = false
  return {
    name: "localized-message-exports",
    enforce: "pre",
    configResolved(config) {
      building = config.command === "build"
    },
    buildStart: { order: "post", sequential: true, handler: generateMessages },
    handleHotUpdate({ file }) {
      if (
        file === compiledMessagesPath ||
        file === resolve(webRoot, "src/paraglide/messages/en.js")
      )
        generateMessages()
    },
    resolveId(id) {
      if (id.startsWith(prefix)) return { id, moduleSideEffects: false }
    },
    load(id) {
      return modules.get(id)
    },
    transform(code, id) {
      if (!building || id !== generatedPath) return
      const source = ts.createSourceFile(id, code, ts.ScriptTarget.Latest, false, ts.ScriptKind.TS)
      const shared: string[] = []
      const messages: { name: string; code: string }[] = []
      for (const statement of source.statements) {
        if (ts.isVariableStatement(statement)) {
          const name = statement.declarationList.declarations[0]?.name
          if (name && ts.isIdentifier(name))
            messages.push({ name: name.text, code: statement.getText(source) })
        } else if (
          ts.isImportDeclaration(statement) &&
          ts.isStringLiteral(statement.moduleSpecifier)
        ) {
          shared.push(
            statement
              .getText(source)
              .replace(
                statement.moduleSpecifier.getText(source),
                JSON.stringify(resolve(dirname(generatedPath), statement.moduleSpecifier.text)),
              ),
          )
        } else shared.push(statement.getText(source))
      }
      for (const message of messages)
        modules.set(`${prefix}${message.name}.ts`, [...shared, message.code].join("\n"))
      return {
        code: messages
          .map(({ name }) => `export { ${name} } from ${JSON.stringify(`${prefix}${name}.ts`)}`)
          .join("\n"),
        map: null,
      }
    },
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  generateMessages()

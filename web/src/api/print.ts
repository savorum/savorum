import { m } from "../lib/messages.ts"
import { client, unwrap } from "./client"
import type { components } from "./schema"

export type PrintOptions = components["schemas"]["PrintOptions"]
export type PrintDocumentInfo = components["schemas"]["PrintDocumentInfo"]
export type PrintFormat = PrintDocumentInfo["format"]

/** Where the recipes in a print come from. */
export interface PrintSource {
  recipes?: string[]
  book?: string
}

/**
 * Generates the document. The response describes it; the bytes are read from
 * the URL it names, and the preview, the download, and printing all read that
 * one document rather than generating it again.
 */
export async function generatePrintDocument(
  source: PrintSource,
  options: PrintOptions,
  signal?: AbortSignal,
): Promise<PrintDocumentInfo> {
  return unwrap(
    await client.POST("/api/v1/print/documents", {
      body: { recipes: source.recipes, book: source.book, options },
      signal,
    }),
    m.print_the_document_could_not_be_generated(),
  )
}

/** The address of the generated bytes, for the viewer and for printing. */
export function printDocumentURL(info: PrintDocumentInfo, download = false): string {
  return download ? `${info.url}?download=true` : info.url
}
